export const PROPERTY_LOAN_DOCUMENTS_TEMPLATE: LoanDocumentItem[] =
  HOME_LOAN_DOCUMENTS_TEMPLATE.map((document) => ({ ...document }));

export function getDocumentsForLoanType(
  loanType: string,
  isBusiness: boolean
): LoanDocumentItem[] {
  if (loanType === "Home Loan") {
    return JSON.parse(JSON.stringify(HOME_LOAN_DOCUMENTS_TEMPLATE));
  }

  const isBusinessCategory =
    isBusiness ||
    [
      "Business Loan",
      "Working Capital",
      "Machinery Loan",
      "Project Finance",
      "MSME Loan",
      "Property Loan",
    ].includes(loanType);

  if (isBusinessCategory) {
    return JSON.parse(JSON.stringify(BUSINESS_DOCUMENTS_TEMPLATE));
  }
  return JSON.parse(JSON.stringify(INDIVIDUAL_DOCUMENTS_TEMPLATE));
}
